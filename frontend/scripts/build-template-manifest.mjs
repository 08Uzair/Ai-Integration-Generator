/**
 * Bundles frontend/engine/templates into a single JS module
 * (engine/src/template-files.js) so the generator can read templates even
 * on serverless hosts (Vercel) where the templates folder is not present
 * on the runtime filesystem at the path the engine expects.
 *
 * Run automatically via `prebuild` / `predev` in frontend/package.json.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const templatesDir = path.resolve(__dirname, '..', 'engine', 'templates');
const outFile = path.resolve(__dirname, '..', 'engine', 'src', 'template-files.js');

async function walk(dir, prefix = '') {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = {};
  for (const entry of entries) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      Object.assign(files, await walk(full, rel));
    } else {
      files[rel] = await fs.readFile(full, 'utf8');
    }
  }
  return files;
}

const files = await walk(templatesDir);
const json = JSON.stringify(files, null, 1);
const header = [
  '// Auto-generated by scripts/build-template-manifest.mjs - DO NOT EDIT.',
  '// Bundled copy of engine/templates so generation works on serverless hosts.',
  'export const TEMPLATE_FILES = ',
].join('\n');
await fs.writeFile(outFile, `${header}${json};\n`, 'utf8');
console.log(`[template-manifest] wrote ${outFile} (${Object.keys(files).length} files)`);
